"""
Οι πληθυσμοί hosts που ομαδοποιούνται χωριστά.

Μέχρι τώρα ο pipeline ήξερε δύο: «εσωτερικοί», δηλαδή το εργαστήριο, και
«εξωτερικοί», δηλαδή όλοι οι άλλοι. Ο διαχωρισμός αποδείχθηκε λάθος: 54
ιδιωτικοί hosts από δύο ακόμη υποδίκτυα περνούσαν ως hosts του διαδικτύου.

Υπάρχουν ΔΥΟ άξονες, και δεν πρέπει να μπερδεύονται:

  - Το ΕΣΩΤΕΡΙΚΟ ΔΙΚΤΥΟ (κλειδί 'micro'). Είναι η ΕΝΩΣΗ όλων των υποδικτύων
    του SUBNET_PREFIXES, δηλαδή 118 hosts, και το micro_global.csv είναι η
    ομαδοποίηση και των τριών μαζί.

  - ΚΑΘΕ ΥΠΟΔΙΚΤΥΟ ΧΩΡΙΣΤΑ (κλειδιά 'subnet_<x>'). Ένας πληθυσμός ανά /24,
    ώστε να συγκρίνονται μεταξύ τους και με την κοινή ομαδοποίηση.

Γι' αυτό το INTERNAL_SUBNET εμφανίζεται ΔΥΟ φορές: μία μέσα στο εσωτερικό
δίκτυο και μία ως ένα από τα υποδίκτυα. Δεν είναι διπλοεγγραφή, είναι οι δύο
άξονες: το micro_global.csv απαντά «πώς ομαδοποιούνται οι 118 μαζί» και το
subnet_192_168_7_global.csv «πώς ομαδοποιούνται οι 64 του εργαστηρίου μόνοι
τους». Τα δύο αρχεία ΔΕΝ βγαίνουν ίδια, και η διαφορά τους είναι ακριβώς το
μέγεθος που μετρά το στάδιο subnets (ARI κοινής προς χωριστή ομαδοποίηση).

Όσο το εσωτερικό δίκτυο είχε ένα μόνο υποδίκτυο, τα δύο σύνολα ταυτίζονταν.
Έπαψε να ισχύει όταν προστέθηκαν τα 192.168.8.x και 192.168.1.x, και η
ξεχωριστή ανάλυση του 192.168.7.x συνέχισε να υπάρχει χωρίς καμία άλλη
αλλαγή — που ήταν και ο λόγος που ο μηχανισμός γράφτηκε έτσι εξαρχής.

Το κλειδί κάθε πληθυσμού είναι το «level» που ήδη χρησιμοποιούν τα στάδια
select_k, micro_profiling και daily_stability, οπότε τα υποδίκτυα μπαίνουν
στον υπάρχοντα μηχανισμό αντί να αποκτήσουν παράλληλο δικό τους.

Ο μακροσκοπικός πληθυσμός ΔΕΝ είναι εδώ: ορίζεται αφαιρετικά (ό,τι δεν είναι
εσωτερικό) και περνά από Isolation Forest πριν την ομαδοποίηση, οπότε δεν
είναι σύνολο hashes αλλά αποτέλεσμα δύο βημάτων· ζει στο data_split.py.
"""
from src.config import (INTERNAL_SUBNET, SUBNET_PREFIXES, MICRO_CLUSTERS,
                        K_PER_LEVEL)
from src.utils.anonymize import get_internal_hashes, get_subnet_hashes

# Το κλειδί του εσωτερικού δικτύου. Μένει 'micro' και δεν γίνεται ποτέ
# 'subnet_...': τα ονόματα των αρχείων του (micro_global.csv,
# summary_kmeans_micro_global.csv) τα διαβάζουν τα στάδια hourly, stability
# και visualize, και τα αποτελέσματα της αναφοράς αναφέρονται σε αυτά.
MICRO = 'micro'


def key_of(prefix):
    """'192.168.8.' -> 'subnet_192_168_8', κλειδί και πρόθεμα αρχείων."""
    return 'subnet_' + prefix.rstrip('.').replace('.', '_')


def title_of(prefix):
    return f'Υποδίκτυο {prefix}x'


def micro_title():
    """
    Ο τίτλος του εσωτερικού δικτύου, ορισμένος μία φορά.

    Τον χρειάζονται και τα γραφήματα: χωρίς αυτόν το υπόμνημα του
    micro_global έγραφε σκέτο «Micro» ενώ των υποδικτύων «Υποδίκτυο
    192.168.8.x», και δεν φαινόταν ποιους hosts δείχνει.
    """
    # Ονομάζει ό,τι περιέχει ο πληθυσμός: όλα τα υποδίκτυα του
    # SUBNET_PREFIXES, όπως ακριβώς τα συνθέτει το get_internal_hashes.
    inside = ', '.join(f'{prefix}x' for prefix in SUBNET_PREFIXES)
    return f'Εσωτερικό δίκτυο ({inside or INTERNAL_SUBNET + "x"})'


def extra_levels():
    """
    (κλειδί, τίτλος) για ΚΑΘΕ υποδίκτυο χωριστά, χωρίς να υπολογιστεί hash.

    Περιλαμβάνεται και το INTERNAL_SUBNET. Τα κλειδιά αυτά γίνονται levels στο
    select_k, γραμμές στο REFERENCE_FILES του daily_stability και πηγές
    γραφημάτων στο plot_results, και το εργαστήριο πρέπει να έχει τα δικά του
    σε όλα — αλλιώς, μόλις το 'micro' γίνει η ομαδοποίηση και των τριών
    υποδικτύων μαζί, η ξεχωριστή ανάλυση του 192.168.7.x θα εξαφανιστεί
    σιωπηλά από τα τρία στάδια.
    """
    return [(key_of(prefix), title_of(prefix)) for prefix in SUBNET_PREFIXES]


def subnet_populations():
    """(κλειδί, τίτλος, hashes) για κάθε υποδίκτυο χωριστά, χωρίς το 'micro'."""
    return [(key_of(prefix), title_of(prefix), get_subnet_hashes(prefix))
            for prefix in SUBNET_PREFIXES]


def populations():
    """
    Κάθε πληθυσμός που ομαδοποιείται, με το εσωτερικό δίκτυο πρώτο.

    Τα hashes υπολογίζονται προς τα εμπρός από το πρόθεμα, όπως και στην
    ανωνυμοποίηση· καμία αντιστροφή.
    """
    return [(MICRO, micro_title(), get_internal_hashes())] + subnet_populations()


def hashes_of(key):
    """Τα hashes ενός πληθυσμού από το κλειδί του."""
    for found_key, _, hashes in populations():
        if found_key == key:
            return hashes
    raise KeyError(f"Άγνωστος πληθυσμός: {key}. "
                   f"Γνωστοί: {', '.join(k for k, _, _ in populations())}")


def default_k(key):
    """
    Το k του config για έναν πληθυσμό.

    Είναι η ΠΡΟΕΠΙΛΟΓΗ, όχι η τελική τιμή: όταν τρέχουμε σε τερματικό, το
    select_k.choose_k δείχνει τον πίνακα των δεικτών και ρωτά, και η απάντηση
    υπερισχύει. Σε μη διαδραστική εκτέλεση (ανακατευθυνόμενη έξοδος, cron)
    ισχύει αυτό εδώ, και γι' αυτό πρέπει να είναι το k της αναφοράς και όχι
    ένα σκέτο MICRO_CLUSTERS για όλους.

    Το fallback στο MICRO_CLUSTERS μένει για πληθυσμό που προστέθηκε στο
    SUBNET_PREFIXES χωρίς εγγραφή στο K_PER_LEVEL: προτιμώ να τρέξει με
    προεπιλογή και να το πιάσουν οι έλεγχοι, από το να σκάσει στη μέση του
    pipeline. Το run_manifest.json καταγράφει πάντα τι χρησιμοποιήθηκε.
    """
    return K_PER_LEVEL.get(key, MICRO_CLUSTERS)

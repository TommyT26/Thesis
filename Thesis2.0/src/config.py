# 2. Ρυθμίσεις Δικτύου
#
# Τα ιδιωτικά υποδίκτυα της σχολής. Η λίστα αυτή είναι η ΜΟΝΗ πηγή αλήθειας
# για το «ποιο δίκτυο είναι δικό μας», και ορίζει ταυτόχρονα δύο πράγματα:
#
#   α) το ΕΣΩΤΕΡΙΚΟ ΔΙΚΤΥΟ, δηλαδή την ένωσή τους (118 hosts) — αυτό που
#      ομαδοποιεί το στάδιο micro και αυτό που ΔΕΝ είναι «εξωτερικό» στο macro,
#   β) έναν χωριστό πληθυσμό ανά /24, που αναλύει το στάδιο subnets.
#
# Τα 192.168.8.x και 192.168.1.x προστέθηκαν επειδή μετρήθηκε ότι πέρναγαν
# στην ανάλυση ως «εξωτερικοί hosts του διαδικτύου», με το 29,1% των ροών: 25
# hosts στο 192.168.8.x και 29 στο 192.168.1.x. Η ένδειξη των μετρήσεων είναι
# ότι είναι υποδομή του ίδιου δικτύου (εκτυπωτές και διαχειριζόμενοι σταθμοί).
# Αν το εργαστήριο πει ότι ανήκουν σε άλλο τμήμα, αφαιρούνται ΑΠΟ ΕΔΩ και
# ξανατρέχει το pipeline — καμία άλλη αλλαγή στον κώδικα.
#
# Το πρώτο στοιχείο είναι το εργαστήριο και παίζει δύο ρόλους: είναι ένα από
# τα υποδίκτυα, και είναι η ομάδα αναφοράς με την οποία συγκρίνονται τα άλλα
# στο στάδιο subnets. Η σειρά έχει σημασία γι' αυτόν τον λόγο και μόνο.
SUBNET_PREFIXES = ['192.168.7.', '192.168.8.', '192.168.1.']

if not SUBNET_PREFIXES:
    raise ValueError(
        "ΣΦΑΛΜΑ: η SUBNET_PREFIXES δεν μπορεί να είναι κενή — χωρίς αυτήν δεν "
        "ορίζεται ποιοι hosts είναι εσωτερικοί και ο διαχωρισμός καταρρέει.")

# Το δηλωμένο «εσωτερικό» υποδίκτυο, δηλαδή το εργαστήριο.
#
# ΔΕΝ είναι ανεξάρτητη ρύθμιση: παράγεται από τη λίστα παραπάνω. Ήταν
# ανεξάρτητη, και αυτό ήταν παγίδα — μια αλλαγή στη SUBNET_PREFIXES χωρίς
# αντίστοιχη αλλαγή εδώ έδινε στο στάδιο subnets ομάδα αναφοράς που δεν
# συμμετέχει στην ανάλυση, σιωπηλά. Τώρα δεν μπορούν να αποκλίνουν.
INTERNAL_SUBNET = SUBNET_PREFIXES[0]

# Εύρος k για την ΚΟΙΝΗ ομαδοποίηση των 118 ιδιωτικών hosts στο στάδιο
# 'subnets'.
#
# Προσοχή στο τι ΔΕΝ είναι: δεν επιλέγει k για κανένα υποδίκτυο. Τα k των
# υποδικτύων βγαίνουν από το kselect και το K_PER_LEVEL, και το στάδιο
# 'subnets' διαβάζει έτοιμες τις ετικέτες του micro (read_separate_labels).
# Παλιότερα το στάδιο έκανε και δική του επιλογή με σκέτο silhouette, που
# απέκλινε από το kselect· καταργήθηκε ώστε να υπάρχει μία ομαδοποίηση.
#
# Εδώ το εύρος χρησιμεύει για να σαρωθεί η ΚΟΙΝΗ ομαδοποίηση σε κάθε k και να
# γραφτούν για καθένα το ARI προς το υποδίκτυο, ο σταυροπίνακας και η συμφωνία
# κοινής προς χωριστή. Αυτά εξαρτώνται έντονα από το k, οπότε ένα νούμερο
# χωρίς την καμπύλη του δεν ελέγχεται.
SUBNET_K_RANGE = range(2, 9)

# Ελάχιστες ροές για να μπει ένας host στην ωριαία καμπύλη των υποδικτύων.
#
# Η κανονικοποίηση γίνεται ανά host, ώστε ένας τεράστιος host να μην ορίζει
# μόνος του την καμπύλη της ομάδας. Το τίμημα είναι στην άλλη άκρη: ένας host
# με δύο ροές μετράει ΟΣΟ κι ένας με ένα εκατομμύριο, και αν οι δύο ροές του
# έτυχαν στην ίδια ώρα συνεισφέρει κορυφή ύψους 100% εκεί. Στο 192.168.1.x
# ένας τέτοιος host έφτιαχνε τις 3,45 από τις 8,38 μονάδες της κορυφής των
# 18:00: η καμπύλη έδειχνε απογευματινό ωράριο εκεί που η εντροπία ώρας
# έλεγε 0,998, δηλαδή σχεδόν σταθερό ρυθμό.
#
# Το 24 είναι μία ροή ανά ώρα κατά μέσο όρο: κάτω από αυτό δεν υπάρχει
# κατανομή μέσα στο 24ωρο για να μετρηθεί. Αφορά ΜΟΝΟ το στάδιο subnets· το
# στάδιο hourly δεν έχει κατώφλι, επειδή οι ομάδες του έχουν χιλιάδες hosts
# και ο θόρυβος εξομαλύνεται.
SUBNET_MIN_FLOWS_HOURLY = 24

